export const PAGES: Record<Lang, PagesText> = { en, es, pa, hi, ru, uk, fr };

/** The driver's app-language words for the driver app's pages. */
export function usePagesText(): PagesText {
  const { lang } = useDriverUi();
  return PAGES[lang];
}

/** How a driver is paid, in their words ("28% of the load"). */
export function payWords(p: PagesText, driver: Driver): string {
  if (driver.payType === "percentage") return p.earn.payType.percentage(`${Math.round(driver.payRate * 100)}%`);
  if (driver.payType === "hourly") return p.earn.payType.hourly(`$${driver.payRate.toFixed(2)}`);
  if (driver.payType === "per_move") return p.earn.payType.per_move(`$${Math.round(driver.payRate)}`);
  return p.earn.payType.per_mile(`$${driver.payRate.toFixed(2)}`);
}

/** The headline and the small "Backroute · …" line on a load page, by stage. */
export function stageNote(p: PagesText, stage: LoadStage): string {
  if (stage === "negotiating") return p.note.negotiating;
  if (stage === "rate_confirmed" || stage === "booked") return p.note.dispatching;
  if (stage === "delivered") return p.note.complete;
  if (stage === "dispatched" || stage === "at_pickup" || stage === "in_transit" || stage === "at_delivery") return p.note.monitoring;
  return "Backroute";
}
