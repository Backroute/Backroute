export const TRIP: Record<Lang, TripText> = { en, es, pa, hi, ru, uk, fr };
export const TRIP_EN = en;

/** The trip cards' words for whoever's looking: the driver's app language, or English for the owner's view. */
export function useTripText(viewer: "driver" | "carrier" = "driver"): TripText {
  const { lang } = useDriverUi();
  return viewer === "driver" ? TRIP[lang] : en;
}

/** The next step and the drive line, said in `w`'s language. */
export function nextWords(w: TripText, s: TripState): string {
  return w.next[s.next.key];
}
export function driveWords(w: TripText, s: TripState): string {
  return s.driveKey ? w.drive[s.driveKey] : s.drive;
}
